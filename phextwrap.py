#!/usr/bin/env python3
"""phextwrap - wrap a .phext volume into a .bas data include for
libphext-bas (BASIC PHEXT), mechanically.

The volume rides VERBATIM: this tool performs no parsing, no
translation, and no re-encoding of the content. It splits the
volume's bytes into string-literal runs and CHR$(n) terms and
emits one phLoadVolume subroutine that concatenates the terms
back into phVol$, byte for byte the input volume. libphext.bas
then parses phVol$ as phext at setup. (Verified on the local
runner: every phext dimension-break byte, \\x01 and \\x17-\\x1F,
is legal raw inside a bassy string literal; only the quote
itself and the line breaks LF/CR need CHR$ spelling, since a
literal cannot contain its delimiter or span source lines.)

Why literals: bassy 0.1.0 (treeform/bassy) has no DATA / READ /
RESTORE statements - its keyword table (bassy.nim) contains none
of them. The engine's existing data flow for text is the source
file itself: string literals materialized at setup, in globals
that restart() preserves across decisions.

USAGE: phextwrap.py VOLUME.phext [-o OUT.bas]
Prints the volume and include sha256 values.
"""
import argparse, hashlib, sys

MAX_RUN = 120  # literal run length cap, for source readability

# Bytes that cannot ride raw inside a bassy string literal: the
# quote (the literal's delimiter) and LF/CR (a literal cannot
# span source lines). Everything else - including all nine phext
# dimension-break bytes - rides raw.
NEEDS_CHR = {0x22, 0x0A, 0x0D}


def terms(data: bytes):
    """Yield ('lit', raw_bytes) or ('chr', byte) terms covering data."""
    run = bytearray()
    for b in data:
        if b not in NEEDS_CHR:
            run.append(b)
            if len(run) >= MAX_RUN:
                yield "lit", bytes(run)
                run = bytearray()
        else:
            if run:
                yield "lit", bytes(run)
                run = bytearray()
            yield "chr", b
    if run:
        yield "lit", bytes(run)


def emit(data: bytes, source_name: str, source_sha: str) -> bytes:
    lines = [
        b"' PHEXT VOLUME include - generated by phextwrap; DO NOT EDIT.",
        f"' source volume: {source_name} ({len(data)} bytes)".encode(),
        f"' source sha256: {source_sha}".encode(),
        b"' The volume rides verbatim: literal runs and CHR$ terms",
        b"' concatenate at setup into phVol$, byte for byte the",
        b"' source volume. libphext.bas parses it as phext.",
        b"phLoadVolume:",
        b'phVol$ = ""',
    ]
    for kind, val in terms(data):
        if kind == "lit":
            lines.append(b'phVol$ = phVol$ + "' + val + b'"')
        else:
            lines.append(f"phVol$ = phVol$ + CHR$({val})".encode())
    lines.append(b"RETURN")
    return b"\n".join(lines) + b"\n"


CHUNK_MAX = 1000
CHUNK_SLOTS = 64


def chunks(data: bytes):
    """Fixed CHUNK_MAX slices of the volume. The generation-1
    walker in libphext.bas is a resumable byte stream - chunk
    boundaries may fall anywhere (mid-scroll, mid-token,
    mid-break-run) without changing the parse."""
    out = [data[i:i + CHUNK_MAX] for i in range(0, len(data), CHUNK_MAX)]
    if len(out) > CHUNK_SLOTS:
        raise ValueError(
            f"volume needs {len(out)} chunks; phChunk$ holds {CHUNK_SLOTS}")
    return out


def chunk_terms(part: bytes):
    """Terms for one chunk, with literal runs up to the whole chunk:
    a chunk free of quote/LF/CR is exactly ONE literal."""
    run = bytearray()
    for b in part:
        if b not in NEEDS_CHR:
            run.append(b)
        else:
            if run:
                yield "lit", bytes(run)
                run = bytearray()
            yield "chr", b
    if run:
        yield "lit", bytes(run)


def emit_chunked(data: bytes, source_name: str, source_sha: str):
    """The chunked include for libphext-bas generation 1: the
    volume rides as phChunk$() entries parsed incrementally
    across decisions (phParseStep). Each chunk is emitted as ONE
    string literal whenever the bytes allow: a materialized
    literal is rooted for the whole episode in bassy, so one
    literal per chunk is the span-economical form - a volume
    authored without quote/LF/CR bytes (the phextwrap chunked
    contract) costs exactly one rooted span per chunk."""
    parts = chunks(data)
    nlit = 0
    lines = [
        b"' PHEXT VOLUME include, chunked - generated by phextwrap; DO NOT EDIT.",
        f"' source volume: {source_name} ({len(data)} bytes)".encode(),
        f"' source sha256: {source_sha}".encode(),
        b"' The volume rides as chunks in phChunk$(); libphext.bas",
        b"' parses it incrementally (phParseStep) across decisions.",
        b"phLoadVolume:",
        b"phChunked = 1",
        f"phChunkN = {len(parts)}".encode(),
    ]
    for i, part in enumerate(parts):
        exprs = []
        for kind, val in chunk_terms(part):
            if kind == "lit":
                nlit += 1
                exprs.append(b'"' + val + b'"')
            else:
                exprs.append(f"CHR$({val})".encode())
        lines.append(f"phChunk$({i}) = ".encode() + b" + ".join(exprs))
    lines.append(b"RETURN")
    return b"\n".join(lines) + b"\n", len(parts), nlit


def main():
    ap = argparse.ArgumentParser(description="Wrap a .phext volume into a "
                                             "libphext-bas data include.")
    ap.add_argument("volume")
    ap.add_argument("-o", "--out")
    ap.add_argument("--chunked", action="store_true",
                    help="emit the generation-1 chunked include "
                         "(phChunk$ + incremental parse)")
    args = ap.parse_args()
    data = open(args.volume, "rb").read()
    source_sha = hashlib.sha256(data).hexdigest()
    if args.chunked:
        out, nchunks, nlit = emit_chunked(data, args.volume, source_sha)
        print(f"phextwrap: chunked into {nchunks} chunks, {nlit} literals",
              file=sys.stderr)
    else:
        out = emit(data, args.volume, source_sha)
    if args.out:
        open(args.out, "wb").write(out)
    else:
        sys.stdout.buffer.write(out)
    print(f"phextwrap: volume {len(data)} bytes sha256 {source_sha}; "
          f"include sha256 {hashlib.sha256(out).hexdigest()}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
